import assert from "node:assert/strict";
import { readFileSync } from "node:fs";

const normalizeLf = (source) => source.replace(/\r\n?/g, "\n");
const css = normalizeLf(
  readFileSync(new URL("../theme.css", import.meta.url), "utf8")
);
const injector = readFileSync(
  new URL("../inject-kami-snippet.js", import.meta.url),
  "utf8"
);

const encoded = injector.match(/const b64 = "([A-Za-z0-9+/=]+)";/)?.[1];
assert.ok(encoded, "inject-kami-snippet.js must contain the generated base64 payload");
assert.equal(Buffer.from(encoded, "base64").toString("utf8"), css);

const lineCount = css.split("\n").length - 1;
const byteCount = Buffer.byteLength(css, "utf8");
assert.match(
  injector,
  new RegExp(`Auto-generated by sync\\.sh from theme\\.css \\(${lineCount} lines, ${byteCount} bytes\\)`)
);

console.log("Generated injector matches canonical UTF-8/LF theme.css.");
